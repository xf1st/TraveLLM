/**
 * Strict Rules - Правила анти-галлюцинаций для AI
 * Жёсткие инструкции чтобы AI не придумывал
 */

export const STRICT_RULES = `
=== СТРОГИЕ ПРАВИЛА (НАРУШЕНИЕ = ОШИБКА) ===

ЗАПРЕЩЕНО:
1. ВЫДУМЫВАТЬ названия отелей, ресторанов, кафе которых не существует
2. УКАЗЫВАТЬ несуществующие адреса и телефоны
3. ГЕНЕРИРОВАТЬ фейковые отзывы и рейтинги
4. ПРИДУМЫВАТЬ цены без реальных данных
5. ИГНОРИРОВАТЬ переданный контекст с реальными данными
6. СТАВИТЬ утренние активности после ночного перелёта (минимум 3 часа на отдых)
7. ПЛАНИРОВАТЬ больше 3-4 активностей в день (реалистично!)
8. ЗАБЫВАТЬ про время на переезды между локациями
9. РЕКОМЕНДОВАТЬ закрытые места или места с плохими отзывами

ОБЯЗАТЕЛЬНО:
1. ИСПОЛЬЗОВАТЬ переданные данные о рейсах и ценах
2. УЧИТЫВАТЬ переданные события и праздники
3. ВКЛЮЧАТЬ время на еду (завтрак, обед, ужин)
4. УЧИТЫВАТЬ часовые пояса при расчёте времени
5. ДАВАТЬ реалистичные оценки времени на активности
6. УКАЗЫВАТЬ если что-то требует предварительного бронирования
7. УЧИТЫВАТЬ погоду и сезон
8. СОБЛЮДАТЬ логику маршрута (не метаться по городу)

ФОРМАТ ОТВЕТА:
- Стоимость ТОЛЬКО в поле "cost", НЕ в описании
- Ссылки на билеты ТОЛЬКО в поле "link", НЕ в тексте
- Время в формате "HH:MM"
- Все цены в рублях если не указано иное
- Описания краткие, по делу (максимум 2 предложения)

ЕСЛИ ДАННЫЕ НЕДОСТУПНЫ:
- Указывай "Цену уточнять на месте" вместо выдумывания
- Используй общие рекомендации без конкретных названий
- Честно пиши что информация может устареть
`.trim()

/**
 * Дополнительные правила для конкретных ситуаций
 */
export const SITUATION_RULES: Record<string, string> = {
    first_day_late_arrival: `
ПЕРВЫЙ ДЕНЬ - ПОЗДНЕЕ ПРИБЫТИЕ:
- Если прилёт после 18:00 - только трансфер + ужин + отдых
- Если прилёт после 22:00 - только трансфер + отдых
- НЕ планировать музеи/экскурсии в день прилёта
`.trim(),

    last_day_early_departure: `
ПОСЛЕДНИЙ ДЕНЬ - РАННИЙ ВЫЛЕТ:
- Если вылет до 10:00 - только завтрак + трансфер
- Если вылет до 14:00 - максимум одна утренняя активность
- Учитывать время на дорогу до аэропорта + 2-3 часа до вылета
`.trim(),

    budget_travel: `
БЮДЖЕТНОЕ ПУТЕШЕСТВИЕ:
- Приоритет бесплатным активностям
- Указывать экономные альтернативы
- Уличная еда и рынки вместо ресторанов
- Общественный транспорт вместо такси
`.trim(),

    luxury_travel: `
ЛЮКС ПУТЕШЕСТВИЕ:
- Только премиальные опции
- Конкретные названия 5* отелей
- VIP-сервис и приватные туры
- Мишлен-рестораны и rooftop бары
`.trim(),

    family_travel: `
СЕМЕЙНОЕ ПУТЕШЕСТВИЕ:
- Детские активности обязательны
- Перерывы на отдых каждые 2-3 часа
- Рестораны с детским меню
- Избегать поздних мероприятий
`.trim(),

    rainy_season: `
СЕЗОН ДОЖДЕЙ:
- Планировать indoor активности как backup
- Утренние экскурсии (дождь обычно после обеда)
- Указывать крытые альтернативы
`.trim(),

    ramadan: `
РАМАДАН:
- Многие заведения закрыты днём
- Еда в туристических районах доступна
- Вечером (после ифтара) всё оживает
- Уважать местные традиции
`.trim()
}

/**
 * Получить все применимые правила для контекста
 */
export function getApplicableRules(context: {
    isFirstDayLateArrival?: boolean
    isLastDayEarlyDeparture?: boolean
    travelStyle?: string
    isRainySeason?: boolean
    isRamadan?: boolean
}): string {
    const rules: string[] = [STRICT_RULES]

    if (context.isFirstDayLateArrival) {
        rules.push(SITUATION_RULES.first_day_late_arrival)
    }
    if (context.isLastDayEarlyDeparture) {
        rules.push(SITUATION_RULES.last_day_early_departure)
    }
    if (context.travelStyle === "budget") {
        rules.push(SITUATION_RULES.budget_travel)
    }
    if (context.travelStyle === "luxury") {
        rules.push(SITUATION_RULES.luxury_travel)
    }
    if (context.travelStyle === "family") {
        rules.push(SITUATION_RULES.family_travel)
    }
    if (context.isRainySeason) {
        rules.push(SITUATION_RULES.rainy_season)
    }
    if (context.isRamadan) {
        rules.push(SITUATION_RULES.ramadan)
    }

    return rules.join("\n\n")
}
